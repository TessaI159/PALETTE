static const char *inst_set_name(enum InstSet inst) {
  switch (inst) {
  case AVX:
    return "AVX2+FMA";
  case SSE:
    return "SSE4.1";
  case FB:
    return "Scalar Fallback";
  default:
    return "Unknown";
  }
}

static inline float clampf(float v, float min, float max) {
  if (v < min)
    return min;
  if (v > max)
    return max;
  return v;
}

static void generate_test_image(struct Color *img, uint32_t num) {
  /* Generate a synthetic scene with 4 color clusters:
     1. Sky Blue (R: 0.35, G: 0.65, B: 0.95)
     2. Foliage Green (R: 0.15, G: 0.60, B: 0.25)
     3. Sunset Orange (R: 0.95, G: 0.45, B: 0.15)
     4. Deep Ocean (R: 0.05, G: 0.15, B: 0.40)
     Just kidding. I never ended up using the image generated by Gemini because
     I didn't have an image reader.
  */

  float bases[4][3] = {{0.35f, 0.65f, 0.95f},
                       {0.15f, 0.6f, 0.25f},
                       {0.95f, 0.45f, 0.15f},
                       {0.05f, 0.15f, 0.40f}};
  srand(42);
  for (uint32_t i = 0; i < num; ++i) {
    int cluster = rand() % 4;
    float noise_r = ((float)(rand() % 100) - 50.0f) / 5000.0f;
    float noise_g = ((float)(rand() % 100) - 50.0f) / 5000.0f;
    float noise_b = ((float)(rand() % 100) - 50.0f) / 5000.0f;

    Color_set(img, i, clampf(bases[cluster][0] + noise_r, 0.0f, 1.0f),
              clampf(bases[cluster][1] + noise_g, 0.0f, 1.0f),
              clampf(bases[cluster][2] + noise_b, 0.0f, 1.0f));
  }
}

int main(int argc, char **argv) {
  (void)argc;
  (void)argv;

  printf("\n==================================================================="
         "=======\n");
  printf("   PALETTE - Perceived Average of Light in Each Temporal Tile "
         "Extracted\n");
  printf("====================================================================="
         "=====\n\n");

  /* 1. Hardware & SIMD Query */
  query_features(&features);
  printf("[CPU Detection]\n");
  printf("  -- Logical cores:  %u\n", features.logical_cores);
  printf("  -- Physical cores: %u\n", features.physical_cores);

  if (features.l[1] > 0)
    printf("  -- L1 Cache:       %" PRIu64 " KB\n", features.l[1] / 1024);

  if (features.l[2] > 0)
    printf("  -- L2 Cache:       %" PRIu64 " KB\n", features.l[2] / 1024);

  if (features.l[3] > 0)
    printf("  -- L3 Cache:       %" PRIu64 " KB\n", features.l[3] / 1024);

  printf(" -- Active Dispatch Engine: %s\n\n",
         inst_set_name(features.instructions));

  /* 2. Configure PALETTE parameters */

  g_params.space = OK;
  g_params.diff_fn = EUCLIDEAN;
  g_params.cw = false;

  const uint32_t num_pixels = 20000;
  printf("[Processing %u Pixels in SoA Layout]\n", num_pixels);

  struct Color scene;
  if (!Color_alloc(&scene, num_pixels)) {
    fprintf(stderr, "Failed to allocate memory for color buffer.\n");
    return 1;
  }

  generate_test_image(&scene, num_pixels);

  /* 3. Color Space Conversion to Oklab */
  clock_t tic = clock();
  srgb_to_oklab(&scene);
  clock_t toc = clock();
  double conv_ms = (double)(toc - tic) * 1000.0 / CLOCKS_PER_SEC;
  printf("  -- Linear sRGB -> Oklab converserion: %.3f ms\n", conv_ms);

  /* 4. KMeans Palette Extraction */
  struct kmeans_params km_params = {
      .k = 4, .max_iters = 200, .tolerance = 1e-4f, .seed = 2221994};

  struct kmeans_result km_res;
  tic = clock();
  if (!kmeans_run(&scene, &km_params, &km_res)) {
    fprintf(stderr, "KMeans clustering failed.\n");
    Color_free(&scene);
    return 1;
  }
  toc = clock();
  double km_ms = (double)(toc - tic) * 1000.0 / CLOCKS_PER_SEC;

  printf("  -- KMeans clustering converged in %u iterations (%.3f ms)\n",
         km_res.iters_run, km_ms);
  printf("  -- Final cluster inertia: %.2f\n\n", km_res.inertia);

  /* 5. Convert Extracted Centroid Back to sRGB */
  oklab_to_srgb(&km_res.centroids);

  printf("[Extracted Dominant Color Palette]\n");
  for (uint8_t j = 0; j < km_params.k; ++j) {
    float r_lin = km_res.centroids.alpha[j];
    float g_lin = km_res.centroids.beta[j];
    float b_lin = km_res.centroids.gamma[j];

    /* Delinearize to gamma sRGB sRGB [0,255] */
    int r = (int)roundf(clampf(
        powf(clampf(r_lin, 0.0f, 1.0f), 1.0f / 2.2f) * 255.0f, 0.0f, 255.0f));
    int g = (int)roundf(clampf(
        powf(clampf(g_lin, 0.0f, 1.0f), 1.0f / 2.2f) * 255.0f, 0.0f, 255.0f));
    int b = (int)roundf(clampf(
        powf(clampf(b_lin, 0.0f, 1.0f), 1.0f / 2.2f) * 255.0f, 0.0f, 255.0f));

    /* Render 24-bit ANSI truecolor block */
    printf("  Color %u \033[48;2;%d;%d;%dm      \033[0m #%02X%02X%02X (RGB: "
           "%3d, %3d, %3d)\n",
           j + 1, r, g, b, r, g, b, r, g, b);
  }

  printf("\nTotal pipeline Elapsed Time: %.3f ms\n", conv_ms + km_ms);

  printf("===============================================================\n\n");

  /* Clean Up */
  kmeans_result_free(&km_res);
  Color_free(&scene);

  return 0;
}
